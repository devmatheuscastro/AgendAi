-- Execute conectado ao banco agendai, como seu proprietário.
-- O servidor e `python manage.py init-db` também aplicam este arquivo.
-- Não apaga dados existentes. PostgreSQL 14+.
CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    password TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('paciente','profissional','atendente','admin')),
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users (lower(email));

CREATE TABLE IF NOT EXISTS doctors (
    id TEXT PRIMARY KEY REFERENCES users(id),
    specialty TEXT NOT NULL,
    price INTEGER NOT NULL CHECK (price >= 0),
    photo TEXT NOT NULL DEFAULT 'default.svg'
);
CREATE TABLE IF NOT EXISTS availability (
    doctor TEXT NOT NULL REFERENCES doctors(id),
    day TEXT NOT NULL,
    hours TEXT NOT NULL CHECK (jsonb_typeof(hours::jsonb) = 'array'),
    PRIMARY KEY (doctor, day),
    CHECK (day = '*' OR day ~ '^\d{4}-\d{2}-\d{2}$')
);
CREATE TABLE IF NOT EXISTS appointments (
    id TEXT PRIMARY KEY,
    doctor TEXT NOT NULL REFERENCES doctors(id),
    patient_id TEXT NOT NULL REFERENCES users(id),
    patient TEXT NOT NULL,
    date DATE NOT NULL,
    time TIME NOT NULL CHECK (time BETWEEN TIME '08:00' AND TIME '18:00'
        AND EXTRACT(MINUTE FROM time) = 0 AND EXTRACT(SECOND FROM time) = 0),
    reason TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'Confirmado' CHECK (status IN ('Confirmado','Cancelado')),
    created_by TEXT NOT NULL REFERENCES users(id),
    cancelled_by TEXT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS doctor_slot ON appointments(doctor,date,time) WHERE status='Confirmado';
CREATE UNIQUE INDEX IF NOT EXISTS patient_slot ON appointments(patient_id,date,time) WHERE status='Confirmado';
CREATE INDEX IF NOT EXISTS appointments_patient_history ON appointments(patient_id,date DESC);

CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id),
    expires DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE TABLE IF NOT EXISTS login_attempts (
    key TEXT PRIMARY KEY,
    count INTEGER NOT NULL DEFAULT 0,
    until DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor TEXT REFERENCES users(id),
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS encounters (
    appointment_id TEXT PRIMARY KEY REFERENCES appointments(id),
    comment TEXT NOT NULL DEFAULT '',
    condition TEXT NOT NULL DEFAULT '',
    referral TEXT NOT NULL DEFAULT '',
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE TABLE IF NOT EXISTS encounter_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id TEXT NOT NULL REFERENCES appointments(id),
    actor TEXT NOT NULL REFERENCES users(id),
    comment TEXT NOT NULL,
    condition TEXT NOT NULL,
    referral TEXT NOT NULL,
    version INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS encounter_revisions_appointment ON encounter_revisions(appointment_id,version);
CREATE TABLE IF NOT EXISTS migrations (name TEXT PRIMARY KEY);
